def test_real_audio_scan_resolve_plan_apply_readback(work_dir: Path) -> None:
    """Full pipeline: scan → resolve → plan → apply → tag readback on real FLAC."""
    library = work_dir / "library"
    album_dir = library / "album1"
    state_db = work_dir / "state.db"

    # ── 1. Scan ──────────────────────────────────────────────────────────
    scanner = LibraryScanner(roots=[library])
    batches = list(scanner.iter_directories())
    assert len(batches) == 1, f"Expected 1 directory batch, got {len(batches)}"
    batch = batches[0]
    assert len(batch.files) == 3, f"Expected 3 audio files, got {len(batch.files)}"

    # Verify files are real audio (non-zero, readable by mutagen)
    for f in batch.files:
        audio = mutagen.File(str(f))
        assert audio is not None, f"mutagen cannot read {f}"
        assert audio.info.length > 0, f"Zero-length audio: {f}"

    # ── 2. Resolve ───────────────────────────────────────────────────────
    store = DirectoryStateStore(state_db)
    try:
        # Extract evidence with a fingerprint reader that maps to our stub release
        fp_reader = _make_fingerprint_reader(batch.files, ALBUM1_RELEASE)
        evidence = extract_evidence(batch.files, fingerprint_reader=fp_reader)
        assert evidence.track_count == 3

        provider = StubProviderClient(ALBUM1_RELEASE)
        outcome = resolve_directory(
            dir_id=batch.dir_id,
            path=batch.directory,
            signature_hash=batch.signature_hash,
            evidence=evidence,
            store=store,
            provider_client=provider,
        )
        assert outcome.state == DirectoryState.RESOLVED_AUTO, (
            f"Expected RESOLVED_AUTO, got {outcome.state}"
        )

        # ── 3. Plan ─────────────────────────────────────────────────────
        record = store.get(batch.dir_id)
        assert record is not None
        assert record.state == DirectoryState.RESOLVED_AUTO

        plan = plan_directory(
            record=record,
            pinned_release=ALBUM1_RELEASE,
            source_files=batch.files,
        )
        assert len(plan.operations) == 3

        # Transition to PLANNED (required by apply_plan preflight)
        store.set_state(
            batch.dir_id,
            DirectoryState.PLANNED,
            pinned_provider=ALBUM1_RELEASE.provider,
            pinned_release_id=ALBUM1_RELEASE.release_id,
        )
        store.record_plan_summary(
            batch.dir_id,
            plan_hash=_stable_plan_hash(plan),
            plan_version=plan.plan_version,
        )

        # ── 4. Build tag patch ───────────────────────────────────────────
        tag_patch = build_tag_patch(
            plan=plan,
            pinned_release=ALBUM1_RELEASE,
            resolution_state=DirectoryState.RESOLVED_AUTO,
        )
        assert tag_patch.allowed is True

        # ── 5. Apply with MutagenTagWriter (real tag writes) ────────────
        tag_writer = MutagenTagWriter()
        report = apply_plan(
            plan=plan,
            tag_patch=tag_patch,
            store=store,
            allowed_roots=(work_dir,),
            dry_run=False,
            tag_writer=tag_writer,
        )
        assert report.status == ApplyStatus.APPLIED, (
            f"Apply failed: {report.errors}"
        )
        assert not report.errors
        assert len(report.tag_ops) == 3

        # ── 6. Read tags back with mutagen directly ──────────────────────
        for op in sorted(plan.operations, key=lambda o: o.track_position):
            dest = _resolve_dest(op.destination_path, work_dir)
            audio = mutagen.File(str(dest))
            assert audio is not None, f"mutagen cannot read applied file {dest}"

            # FLAC stores Vorbis comments — keys are uppercase
            tags = {k.lower(): v[0] if isinstance(v, list) else v for k, v in audio.tags.items()}

            # Album-level tags
            assert tags["album"] == "Integration Test Album", (
                f"album mismatch: {tags.get('album')}"
            )
            assert tags["albumartist"] == "Test Artist", (
                f"albumartist mismatch: {tags.get('albumartist')}"
            )

            # Track-level tags
            expected_track = next(
                t for t in ALBUM1_RELEASE.tracks if t.position == op.track_position
            )
            assert tags["title"] == expected_track.title, (
                f"title mismatch on track {op.track_position}: "
                f"got {tags.get('title')!r}, expected {expected_track.title!r}"
            )
            assert tags["tracknumber"] == str(op.track_position), (
                f"tracknumber mismatch: {tags.get('tracknumber')}"
            )

            # MusicBrainz IDs
            assert tags.get("musicbrainz_albumid") == ALBUM1_RELEASE.release_id
            if expected_track.recording_id:
                assert tags.get("musicbrainz_recordingid") == str(expected_track.recording_id)

            # Provenance tags (prove write happened)
            assert "resonance.prov.version" in tags
            assert tags["resonance.prov.pinned_provider"] == "musicbrainz"

        # ── 7. Verify state transition ───────────────────────────────────
        final_record = store.get(batch.dir_id)
        assert final_record is not None
        assert final_record.state == DirectoryState.APPLIED

    finally:
        store.close()


