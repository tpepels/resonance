class StubProviderClient:
    """Pre-cached provider client — returns deterministic results, no API calls."""

    def __init__(self, release: ProviderRelease) -> None:
        self._release = release

    @property
    def capabilities(self) -> ProviderCapabilities:
        # Fingerprints only — avoids metadata search deduplication issue
        return ProviderCapabilities(supports_fingerprints=True, supports_metadata=False)

    def search_by_fingerprints(self, fingerprints: list[str]) -> list[ProviderRelease]:
        return [self._release]

    def search_by_metadata(
        self, artist: str | None, album: str | None, track_count: int
    ) -> list[ProviderRelease]:
        return []

    def release_by_id(self, provider: str, release_id: str) -> ProviderRelease | None:
        if release_id == self._release.release_id:
            return self._release
        return None


def _stable_plan_hash(plan: Plan) -> str:
    """Reproduce the plan hash used by enricher for record_plan_summary."""
    payload = asdict(plan)

    def convert_paths(obj):
        if isinstance(obj, Path):
            return str(obj)
        if isinstance(obj, dict):
            return {k: convert_paths(v) for k, v in obj.items()}
        if isinstance(obj, (list, tuple)):
            return [convert_paths(item) for item in obj]
        return obj

    payload = convert_paths(payload)
    encoded = json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    return hashlib.sha256(encoded.encode("utf-8")).hexdigest()


# ---------------------------------------------------------------------------
# Fingerprint reader that returns deterministic IDs matching the stub release
# ---------------------------------------------------------------------------
def _make_fingerprint_reader(audio_files: list[Path], release: ProviderRelease):
    """Build a fingerprint reader mapping sorted files → release track fingerprints."""
    sorted_files = sorted(audio_files)
    ordered_tracks = sorted(release.tracks, key=lambda t: t.position)
    fp_map = {}
    for path, track in zip(sorted_files, ordered_tracks):
        fp_map[path.resolve()] = track.fingerprint_id
    return lambda p: fp_map.get(p.resolve())


